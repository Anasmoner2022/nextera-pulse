// One-shot, read-only-source live enrollment refresh. This is not yet the
// incremental progress/transaction/record synchronizer.
package main

import (
	"context"
	"log"
	"nextera-pulse/internal/store"
	pulsesync "nextera-pulse/internal/sync"
	"nextera-pulse/internal/zeroone"
	"os"
	"strconv"
	"time"
)

func envInt(key string, defaultValue int) int {
	if os.Getenv(key) == "" {
		return defaultValue
	}
	n, e := strconv.Atoi(os.Getenv(key))
	if e != nil || n <= 0 {
		log.Fatalf("invalid %s", key)
	}
	return n
}
func main() {
	client, err := zeroone.NewClient(os.Getenv("ZEROONE_GRAPHQL_URL"), os.Getenv("ZEROONE_ACCESS_TOKEN"), nil)
	if err != nil {
		log.Fatal(err)
	}
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		log.Fatal("DATABASE_URL required")
	}
	db, err := store.Connect(dsn)
	if err != nil {
		log.Fatal("database connection failed")
	}
	defer db.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	eventID := envInt("ZEROONE_EVENT_ID", 97)
	cohortID := envInt("PILOT_COHORT_ID", 4)
	result, err := pulsesync.RefreshPilotLevels(ctx, db, client, eventID, cohortID)
	if err != nil {
		log.Fatalf("live enrollment refresh failed: %v", err)
	}
	log.Printf("live refresh succeeded: sourceRows=%d updatedPilotRows=%d unmatchedEventRows=%d", result.SourceRows, result.UpdatedRows, result.UnmatchedRows)
	log.Print("Pace snapshots are NOT regenerated by this command; refresh them separately after validating source data.")
}
